def find_target_paragraph(doc, text, style_contains):
    """查找指定文本和样式的段落，返回 (index, paragraph)。"""
    for i, p in enumerate(doc.paragraphs):
        if p.text.strip() == text and style_contains in (p.style.name if p.style else ''):
            return i, p
    return None, None


def make_paragraph(doc, text, style_name):
    """创建一个新段落，返回其 XML 元素（已从 body 末尾移除）。"""
    p = doc.add_paragraph(text, style=style_name)
    el = p._element
    doc.element.body.remove(el)
    return el, p


def insert_before(target_p, elements):
    """将 elements（XML 元素列表）按顺序插入到 target_p 之前。"""
    for el in elements:
        target_p._element.addprevious(el)


